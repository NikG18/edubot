"""Single current user-facing wording for discounts and commission tiers."""

from __future__ import annotations

from pricing import FAMILY_DISCOUNT_PERCENT, SUBSCRIPTION_PACKAGES


def _student_info_text() -> str:
    package_lines = "\n".join(
        f"• При покупке абонемента на {count} занятий — скидка {discount}%"
        for count, discount in SUBSCRIPTION_PACKAGES
    )
    return (
        "📚 Информация о занятиях для учеников\n\n"
        "Занятия проводятся онлайн в Zoom или Яндекс Телемост. "
        "Ссылку на занятие вы получаете перед уроком.\n"
        "Длительность занятия — 60 или 90 минут.\n\n"
        "🎫 Действующие скидки:\n"
        "• За приведение друга — скидка 10% на все занятия в течение 30 дней\n"
        f"{package_lines}\n"
        f"• Семейная скидка — {FAMILY_DISCOUNT_PERCENT}% для семей, у которых занимаются более одного ребёнка\n\n"
        "Скидки и акции не суммируются. Если одновременно подходят несколько условий, "
        "применяется одно предусмотренное условиями предложение.\n\n"
        "📅 Запись на занятие — через раздел «Запись на занятие».\n"
        "💳 Оплата — через раздел «Оплата».\n"
        "✉️ Вопросы — через «Связь с преподавателем» или «Поддержка»."
    )


def _tutor_info_text() -> str:
    return (
        "👨‍🏫 Информация для преподавателей\n\n"
        "📍 Занятия проводятся онлайн в Zoom или Яндекс Телемост.\n\n"
        "💰 Ученики оплачивают занятия через платформу. Для стороннего репетитора сервис "
        "удерживает агентскую комиссию и перечисляет остаток два раза в месяц — 12-го и 27-го числа.\n\n"
        "📈 Прогрессивная шкала комиссии:\n"
        "• 25% — базовая ставка\n"
        "• 20% — при 21+ проведённом занятии за месяц после 2 полных месяцев работы\n"
        "• 15% — при 41+ проведённом занятии за месяц после 4 месяцев работы\n"
        "• 4-месячное ожидание для 15% можно пройти досрочно: если в течение первых "
        "4 месяцев провести не менее 100 занятий за любой период 60 дней. После такой "
        "разблокировки дальше действует обычное условие 41+ занятий в месяц\n"
        "• Достигнутая пониженная ставка сохраняется ещё на один следующий календарный месяц.\n\n"
        "📝 Задачи преподавателя: подготовка и проведение занятий, обратная связь ученикам, "
        "актуальное расписание и своевременная обработка заявок."
    )


def install_pricing_text_hardening(app) -> None:
    legacy = app.legacy
    legacy.STUDENT_INFO_TEXT = _student_info_text()
    legacy.TUTOR_INFO_TEXT = _tutor_info_text()
